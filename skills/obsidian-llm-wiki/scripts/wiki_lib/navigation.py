"""Derived catalogs use note metadata rather than a second editable truth."""

from __future__ import annotations
from pathlib import Path
from urllib.parse import quote
from .metadata import page, split_page
from .paths import now, safe

GENERATED = {"wiki/index.md", "wiki/concept-table.md", "wiki/log.md"}


def pages(root: Path):
    for path in sorted(safe(root, "wiki").rglob("*.md")):
        relative = path.relative_to(root).as_posix()
        if relative not in GENERATED:
            if path.is_symlink():
                raise ValueError(f"Symlink note: {relative}")
            data, body = split_page(path.read_text(encoding="utf-8"))
            yield relative, data, body


def cell(value) -> str:
    return (
        str(value)
        .replace("|", "\\|")
        .replace("\n", " ")
        .replace("\r", " ")
        .replace("[", "\\[")
        .replace("]", "\\]")
    )


def refresh(root: Path) -> None:
    notes = list(pages(root))
    groups = {}
    concepts = []
    for relative, data, _ in notes:
        groups.setdefault(data.get("type", "other"), []).append((relative, data))
        if relative.startswith("wiki/concepts/"):
            concepts.append((relative, data))
    index = "# Wiki index\n\n"
    index += "- [Concept map](concept-table.md)\n- [Operation history](log.md)\n\n"
    for kind, entries in sorted(groups.items()):
        index += f"## {cell(kind)}\n\n"
        for relative, data in entries:
            label = cell(data.get("title", relative))
            description = cell(data.get("description", ""))
            index += f"- [{label}]({quote(relative[5:])}) — {description}\n"
        index += "\n"
    table = "# Concept map\n\nGenerated from concept-note properties; edit the concept notes, then refresh.\n\n"
    table += (
        "| Concept | Working definition | Sources | Related | Status | Cluster | Maintenance |\n"
        "| --- | --- | --- | --- | --- | --- | --- |\n"
    )
    for relative, data in concepts:
        columns = [
            f'[{cell(data["title"])}]({quote(relative[5:])})',
            cell(data.get("description", "")),
            ", ".join(cell(s) for s in data.get("sources", [])),
            cell(data.get("related", [])),
            cell(data.get("evidence_status", "unreviewed")),
            cell(data.get("cluster", "")),
            cell(data.get("maintenance", "")),
        ]
        table += "| " + " | ".join(columns) + " |\n"
    safe(root, "wiki/index.md").write_text(index, encoding="utf-8", newline="\n")
    safe(root, "wiki/concept-table.md").write_text(
        table, encoding="utf-8", newline="\n"
    )


def append_log(root: Path, operation: str, reason: str) -> None:
    path = safe(root, "wiki/log.md")
    previous = path.read_bytes() if path.exists() else b"# Wiki operation history\n"
    reason = (
        reason.replace("\n", " ")
        .replace("\r", " ")
        .replace("[", "\\[")
        .replace("]", "\\]")
    )
    entry = (
        f"\n## [{now()[:10]}] {operation} | {reason}\n\n"
        "- Generated by obsidian-llm-wiki; approval and fact verification are separate.\n"
    )
    path.write_bytes(previous + entry.encode("utf-8"))
